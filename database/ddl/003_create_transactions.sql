-- PostgreSQL DDL for transaction processing, audit trail, and failure tracking
-- Matches JPA entities: BankTransaction, TransactionAudit, FailedTransaction

CREATE TABLE IF NOT EXISTS bank_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(64) NOT NULL,
    transaction_type VARCHAR(20) NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    source_account_id BIGINT,
    destination_account_id BIGINT,
    status VARCHAR(20) NOT NULL,
    description VARCHAR(255),
    failure_reason VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_bank_transactions_transaction_id UNIQUE (transaction_id),
    CONSTRAINT fk_bank_transactions_source_account FOREIGN KEY (source_account_id)
        REFERENCES accounts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_bank_transactions_dest_account FOREIGN KEY (destination_account_id)
        REFERENCES accounts (id) ON DELETE RESTRICT,
    CONSTRAINT chk_bank_transactions_type CHECK (transaction_type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER')),
    CONSTRAINT chk_bank_transactions_amount_positive CHECK (amount > 0),
    CONSTRAINT chk_bank_transactions_status CHECK (status IN ('SUCCESS', 'FAILED', 'REJECTED')),
    CONSTRAINT chk_bank_transactions_distinct_accounts CHECK (
        source_account_id IS NULL
        OR destination_account_id IS NULL
        OR source_account_id <> destination_account_id
    )
);

CREATE INDEX IF NOT EXISTS idx_bank_transactions_source_account_id
    ON bank_transactions (source_account_id);

CREATE INDEX IF NOT EXISTS idx_bank_transactions_dest_account_id
    ON bank_transactions (destination_account_id);

CREATE INDEX IF NOT EXISTS idx_bank_transactions_status
    ON bank_transactions (status);

CREATE INDEX IF NOT EXISTS idx_bank_transactions_created_at
    ON bank_transactions (created_at);

CREATE TABLE IF NOT EXISTS transaction_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_transaction_id BIGINT NOT NULL,
    transaction_id VARCHAR(64) NOT NULL,
    event_timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    thread_name VARCHAR(100) NOT NULL,
    duration_ms BIGINT NOT NULL DEFAULT 0,
    event_status VARCHAR(20) NOT NULL,
    event_details VARCHAR(500),

    CONSTRAINT fk_transaction_audits_tx FOREIGN KEY (bank_transaction_id)
        REFERENCES bank_transactions (id) ON DELETE CASCADE,
    CONSTRAINT chk_transaction_audits_duration_non_negative CHECK (duration_ms >= 0),
    CONSTRAINT chk_transaction_audits_status CHECK (event_status IN ('SUCCESS', 'FAILED', 'REJECTED'))
);

CREATE INDEX IF NOT EXISTS idx_transaction_audits_bank_tx_id
    ON transaction_audits (bank_transaction_id);

CREATE INDEX IF NOT EXISTS idx_transaction_audits_transaction_id
    ON transaction_audits (transaction_id);

CREATE INDEX IF NOT EXISTS idx_transaction_audits_event_timestamp
    ON transaction_audits (event_timestamp);

CREATE TABLE IF NOT EXISTS failed_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_transaction_id BIGINT NOT NULL,
    transaction_id VARCHAR(64) NOT NULL,
    error_category VARCHAR(100) NOT NULL,
    failure_reason VARCHAR(500) NOT NULL,
    failed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_failed_transactions_bank_tx UNIQUE (bank_transaction_id),
    CONSTRAINT fk_failed_transactions_tx FOREIGN KEY (bank_transaction_id)
        REFERENCES bank_transactions (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_failed_transactions_transaction_id
    ON failed_transactions (transaction_id);

CREATE INDEX IF NOT EXISTS idx_failed_transactions_error_category
    ON failed_transactions (error_category);

CREATE INDEX IF NOT EXISTS idx_failed_transactions_failed_at
    ON failed_transactions (failed_at);
